// `mole rules [--json] [--emit] [--ts-config FILE] [--root DIR]`: run the rules written in decision records.
// Exit 0 clean, 1 violations, 2 rule syntax errors (printed with file:line). --emit writes the generated
// dependency-cruiser config (import rules) and the call rules next to the repo's own config, never over it.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { checkRules } from './check.js';
import { cruiseOptions, depcruiseRuleSet, entryPrefixes } from './compile.js';
import { anyOf, loadRules, pathRegex } from './parse.js';
import { CALL_RULES_FILE, DEPCRUISE_FILE, type RuleSpec, type RulesResult } from './types.js';

/** Write .dependency-cruiser.mole.cjs + .mole-call-rules.json under root; returns the written paths. */
export function emitConfig(root: string, rules: RuleSpec[]): string[] {
  const { forbidden } = depcruiseRuleSet(rules);
  const froms = rules.filter((r) => r.kind === 'import').map((r) => r.from);
  const cjs = [
    '// Generated by `mole rules --emit` from the rules: in .mole/decisions (Mole T27). Do not edit: change the decision record.',
    '// Each rule comment cites its decision, why and record file:line. Mole drops type-only import sites unless a rule says',
    '// types: true (dependency-cruiser cannot tell `import type` of an unresolved module apart); call rules: .mole-call-rules.json.',
    `// Run from the repo root: npx depcruise -c ${DEPCRUISE_FILE} ${froms.length ? entryPrefixes(froms).join(' ') : '.'}   (or any folder containing them, e.g. .)`,
    `module.exports = ${JSON.stringify({ forbidden, options: cruiseOptions(froms) }, null, 2)};`,
    '',
  ].join('\n');
  const calls = rules
    .filter((r) => r.kind === 'call')
    .map((r) => ({
      name: r.name,
      decision: r.decision,
      title: r.title,
      status: r.status,
      callee: r.callee,
      from: r.from,
      fromPath: pathRegex(r.from),
      except: r.except,
      ...(r.except.length ? { exceptPath: anyOf(r.except.map(pathRegex)) } : {}),
      ...(r.why ? { why: r.why } : {}),
      record: `${r.file}:${r.line}`,
    }));
  const a = join(root, DEPCRUISE_FILE);
  const b = join(root, CALL_RULES_FILE);
  writeFileSync(a, cjs);
  writeFileSync(b, `${JSON.stringify(calls, null, 2)}\n`);
  return [a, b];
}

export function formatRules(r: RulesResult): string {
  const out: string[] = [];
  for (const e of r.errors) out.push(`error ${e.file}:${e.line}: ${e.message}`);
  for (const w of r.warnings ?? []) out.push(`warning ${w.file}:${w.line}: ${w.message}`);
  for (const v of r.violations) {
    const d = v.decision;
    out.push(`${v.file}:${v.line}  ${v.kind} ${v.target}  breaks ${d.id} "${d.title}" (${d.flag ? `${d.flag} ` : ''}${d.status})`);
    if (d.why) out.push(`    why: ${d.why}`);
    out.push(`    rule ${v.rule} at ${d.file}:${d.line}`);
  }
  for (const s of r.skipped) out.push(`skipped ${s.decision} ${s.file}:${s.line}: ${s.reason}`);
  const n = (k: RuleSpec['kind']) => r.rules.filter((x) => x.kind === k).length;
  const decisions = new Set(r.rules.map((x) => x.decision)).size;
  out.push(
    `${r.rules.length} rule${r.rules.length === 1 ? '' : 's'} (${n('import')} import, ${n('call')} call) from ${decisions} decision${decisions === 1 ? '' : 's'}: ` +
      `${r.violations.length} violation${r.violations.length === 1 ? '' : 's'}${r.errors.length ? `, ${r.errors.length} rule error${r.errors.length === 1 ? '' : 's'}` : ''} (${r.ms} ms)`,
  );
  if (r.rules.length === 0 && r.errors.length === 0) out.push('mole: no rules (add rules: to a record in .mole/decisions/*.md)');
  return out.join('\n');
}

/** CLI entry used by packages/daemon/src/cli.ts. */
export async function rulesCli(_pos: string[], flags: Record<string, string | true>, root: string): Promise<number> {
  if (flags.emit) {
    const load = loadRules(root);
    if (load.errors.length) {
      for (const e of load.errors) console.error(`error ${e.file}:${e.line}: ${e.message}`);
      return 2;
    }
    for (const w of load.warnings) console.error(`warning ${w.file}:${w.line}: ${w.message}`);
    for (const p of emitConfig(root, load.rules)) console.log(`wrote ${p}`);
    return 0;
  }
  const tsConfig = typeof flags['ts-config'] === 'string' ? flags['ts-config'] : undefined;
  const r = await checkRules(root, { tsConfig });
  console.log(flags.json ? JSON.stringify(r, null, 2) : formatRules(r));
  return r.errors.length ? 2 : r.violations.length ? 1 : 0;
}

