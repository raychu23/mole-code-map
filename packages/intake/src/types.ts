// Types for T23 decision-traces intake: agents interrogate, people write (D38).
// Mole never drafts a record's why/(internal reference removed) (R6); it only gathers evidence already on disk/in git
// and phrases up to 3 pointed questions + assumption checks over that evidence.

export type AssumptionCheck = 'no_alternatives' | 'scope_not_anchored' | 'contradicts_tenet' | 'stale_citation';

/** Where a fact lives: a real commit, a file:line, or a transcript id — never invented (M30b). */
export interface EvidenceItem {
  kind: 'commit' | 'file_line' | 'transcript';
  /** full git sha (commit) */
  commit?: string;
  /** repo-relative path (file_line) */
  file?: string;
  /** 1-based line (file_line) */
  line?: number;
  /** harness session/transcript identifier (transcript) */
  transcriptId?: string;
  /** short human label for the question text, never the fact itself */
  label: string;
}

/** One assumption-check finding on a person-written record (no generated prose — only the check id + cited evidence). */
export interface Finding {
  check: AssumptionCheck;
  recordId: string;
  file: string;
  line: number;
  /** fixed, deterministic template text (never model-generated by default; see QUESTION_TEMPLATES) */
  question: string;
  evidence: EvidenceItem[];
}

/** One pointed question asked of the author of a code change (reuses @mole/questions + @mole/decisions facts). */
export interface InterrogateQuestion {
  rank: number;
  check: AssumptionCheck | 'past-fix' | 'note' | 'guard-test' | 'seen';
  text: string;
  evidence: EvidenceItem[];
}

export interface InterrogateResult {
  /** false = nothing governs the change -> silent (done-when 5) */
  governed: boolean;
  governingDecisions: string[];
  questions: InterrogateQuestion[];
  evidence: EvidenceItem[];
  modelCalls: number;
}

export const MAX_QUESTIONS = 3;
