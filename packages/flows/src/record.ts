// `mole flows record`: run the repo's vitest with the flows plugin + a setup file that marks each test, then collect
// the per-test flows the workers wrote. Everything generated (wrapper config, setup file, Vite cache) lives in the
// store dir, so the target repo is never written to (the Excalidraw clone is shared and read-only).
import { spawn } from 'node:child_process';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { writeMeta } from './store.js';
import type { RecordOptions, RecordResult } from './types.js';

const self = dirname(fileURLToPath(import.meta.url));
// the setup file and the plugin are loaded by the target's vitest from the built package (dist/src), also when this
// module itself runs from source under our own tests
const here = existsSync(join(self, 'runtime.js')) ? self : resolve(self, '../dist/src');
const flowsPkg = dirname(findUp(self, 'package.json') ?? join(self, '../package.json'));

const CONFIGS = ['vitest.config.ts', 'vitest.config.mts', 'vitest.config.js', 'vitest.config.mjs', 'vite.config.ts', 'vite.config.mts', 'vite.config.js', 'vite.config.mjs'];

function findUp(start: string, rel: string): string | undefined {
  for (let d = resolve(start); ; d = dirname(d)) {
    if (existsSync(join(d, rel))) return join(d, rel);
    if (dirname(d) === d) return undefined;
  }
}

/** the target repo's own vitest (the instance its test files import), not ours */
function vitestOf(root: string): { pkg: string; bin: string; entry: string } {
  let pkgJson: string | undefined;
  try {
    pkgJson = createRequire(join(root, 'noop.js')).resolve('vitest/package.json');
  } catch {
    pkgJson = findUp(root, 'node_modules/vitest/package.json');
  }
  if (!pkgJson) throw new Error(`no vitest installed for ${root}`);
  const pkg = dirname(pkgJson);
  const meta = JSON.parse(readFileSync(pkgJson, 'utf8')) as { exports?: Record<string, unknown> };
  const dot = meta.exports?.['.'] as Record<string, unknown> | string | undefined;
  const pick = (v: unknown): string | undefined => (typeof v === 'string' ? v : v && typeof v === 'object' ? pick((v as Record<string, unknown>).import ?? (v as Record<string, unknown>).default) : undefined);
  const entry = join(pkg, pick(dot) ?? 'dist/index.js');
  return { pkg, bin: join(pkg, 'vitest.mjs'), entry };
}

function setupFile(vitestEntry: string, out: string, root: string): string {
  const runtime = pathToFileURL(join(here, 'runtime.js')).href;
  return `// generated by mole flows record (T28): marks each test so the flows runtime records per test
import { afterAll, afterEach, beforeEach } from ${JSON.stringify(pathToFileURL(vitestEntry).href)};
import { installRuntime } from ${JSON.stringify(runtime)};
const rt = installRuntime();
const ROOT = ${JSON.stringify(root + '/')};
const OUT = ${JSON.stringify(out)};
let file = '';
let n = 0;
const nameOf = (t) => { const parts = []; for (let x = t; x && x.type !== 'file' && x.name !== undefined; x = x.suite) if (x.name) parts.unshift(x.name); return parts.join(' > '); };
beforeEach((ctx) => {
  const t = ctx.task;
  const fp = (t.file && t.file.filepath) || '';
  file = fp.startsWith(ROOT) ? fp.slice(ROOT.length) : fp;
  rt.begin(nameOf(t), file);
});
afterEach(() => { rt.end(); });
afterAll(() => {
  rt.flush(OUT, (file || 'unknown').replace(/[^A-Za-z0-9._-]+/g, '_') + '-' + process.pid + '-' + (n++) + '-' + Date.now());
});
`;
}

function configFile(o: { base?: string; root: string; out: string; instrument: boolean; setup: string }): string {
  const plugin = pathToFileURL(join(here, 'plugin.js')).href;
  return `// generated by mole flows record (T28): the repo's own vitest config + the flows plugin and setup file
${o.base ? `import base from ${JSON.stringify(o.base)};` : 'const base = {};'}
import { resolve as __resolve } from 'node:path';
const PLUGIN = [${JSON.stringify(plugin)}].join('');
export default async (env) => {
  let b = typeof base === 'function' ? await base(env) : await base;
  b = b || {};
  const test = { ...(b.test || {}) };
  const plugins = [...(b.plugins || [])];
  if (${o.instrument}) {
    const { moleFlowsPlugin } = await import(/* @vite-ignore */ PLUGIN);
    const muted = [].concat(test.setupFiles || []).map((f) => __resolve(${JSON.stringify(o.root)}, f));
    plugins.unshift(moleFlowsPlugin({ root: ${JSON.stringify(o.root)}, muted, exclude: [${JSON.stringify(join(flowsPkg, 'src'))}, ${JSON.stringify(join(flowsPkg, 'dist'))}, ${JSON.stringify(o.out)}] }));
    test.setupFiles = [${JSON.stringify(o.setup)}, ...[].concat(test.setupFiles || [])];
  }
  return { ...b, plugins, cacheDir: ${JSON.stringify(join(o.out, '.vite'))}, test };
};
`;
}

const strip = (s: string): string => s.replace(/\u001b\[[0-9;]*m/g, '');

function counts(output: string): { passed: number; failed: number } {
  const line = strip(output).match(/^\s*Tests\s+(.*)$/m)?.[1] ?? '';
  const num = (re: RegExp): number => Number(line.match(re)?.[1] ?? 0);
  return { passed: num(/(\d+) passed/), failed: num(/(\d+) failed/) };
}

function gitHead(root: string): string {
  try {
    return execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return 'unversioned';
  }
}

/** Run vitest on `files` (default: the whole suite) with instrumentation, store per-test flows in `out`. */
export async function recordFlows(o: RecordOptions): Promise<RecordResult> {
  const root = resolve(o.root);
  const out = resolve(o.out ?? join(root, '.mole/local/flows'));
  const instrument = o.instrument !== false;
  rmSync(join(out, 'tests'), { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const vt = vitestOf(root);
  const baseCfg = o.baseConfig ? resolve(root, o.baseConfig) : CONFIGS.map((c) => join(root, c)).find((c) => existsSync(c));
  const setup = join(out, 'flows.setup.mjs');
  writeFileSync(setup, setupFile(vt.entry, out, root));
  const cfg = join(out, 'vitest.flows.config.mjs');
  writeFileSync(cfg, configFile({ base: baseCfg, root, out, instrument, setup }));
  const files = o.files ?? [];
  const t0 = performance.now();
  const { exit, output } = await new Promise<{ exit: number; output: string }>((done) => {
    const p = spawn(process.execPath, [vt.bin, 'run', '--root', root, '--config', cfg, ...files], { cwd: root, env: { ...process.env, FORCE_COLOR: '0' }, stdio: ['ignore', 'pipe', 'pipe'] });
    let buf = '';
    p.stdout.on('data', (c: Buffer) => (buf += c.toString()));
    p.stderr.on('data', (c: Buffer) => (buf += c.toString()));
    p.on('close', (code) => done({ exit: code ?? 1, output: buf }));
  });
  const wallMs = performance.now() - t0;
  writeFileSync(join(out, 'vitest.log'), output);
  const tests = counts(output);
  let flows = 0;
  const td = join(out, 'tests');
  if (existsSync(td)) {
    for (const f of readdirSync(td)) {
      try {
        flows += (JSON.parse(readFileSync(join(td, f), 'utf8')) as Array<{ test: string }>).filter((t) => t.test !== '(outside tests)').length;
      } catch {
        // partial file
      }
    }
  }
  if (instrument) writeMeta(out, { root, commit: gitHead(root), files, wallMs, exit, tests });
  return { out, wallMs, exit, tests, flows };
}
